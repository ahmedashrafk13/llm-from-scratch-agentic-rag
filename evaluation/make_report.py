"""Render results/*.json and the pre-training log into charts and markdown tables."""
from __future__ import annotations

import json
import math
from pathlib import Path

import matplotlib
import pandas as pd

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

R = Path(__file__).resolve().parents[1] / "results"


def load(name):
    p = R / name
    return json.loads(p.read_text()) if p.exists() else None


def md_table(rows: list[dict], first: str) -> str:
    if not rows:
        return ""
    cols = list(rows[0])
    out = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        out.append("| " + " | ".join(f"{r[c]:.3f}" if isinstance(r[c], float) else str(r[c]) for c in cols) + " |")
    return "\n".join(out)


def loss_curves():
    p = R / "pretrain_log.csv"
    if not p.exists():
        return
    df = pd.read_csv(p)
    fig, ax = plt.subplots(1, 2, figsize=(11, 4))
    ax[0].plot(df.tokens / 1e6, df.train_loss, lw=1, label="train", color="#4C72B0")
    v = df.dropna(subset=["val_tinystories"])
    ax[0].plot(v.tokens / 1e6, v.val_tinystories, "o-", ms=3, label="val TinyStories", color="#DD8452")
    ax[0].plot(v.tokens / 1e6, v.val_fineweb, "s-", ms=3, label="val FineWeb", color="#55A868")
    ax[0].set(xlabel="tokens (M)", ylabel="cross-entropy", title="Pre-training loss")
    ax[0].legend()
    ax[0].grid(alpha=.3)
    ax[1].plot(v.tokens / 1e6, [math.exp(x) for x in v.val_tinystories], "o-", ms=3, label="TinyStories", color="#DD8452")
    ax[1].plot(v.tokens / 1e6, [math.exp(x) for x in v.val_fineweb], "s-", ms=3, label="FineWeb", color="#55A868")
    ax[1].set(xlabel="tokens (M)", ylabel="perplexity (log scale)", title="Validation perplexity", yscale="log")
    ax[1].legend()
    ax[1].grid(alpha=.3)
    fig.tight_layout()
    fig.savefig(R / "pretrain_loss.png", dpi=130)


def bench_chart(b):
    models = [m for m in b if not m.startswith("_")]
    tasks = list(b["_chance"])
    fig, ax = plt.subplots(figsize=(10, 4))
    w = 0.8 / len(models)
    for i, m in enumerate(models):
        ax.bar([t + i * w for t in range(len(tasks))], [b[m].get(k, {}).get("acc_norm", 0) for k in tasks], w, label=m)
    ax.axhline(0.25, ls="--", c="k", lw=1, label="chance")
    ax.set_xticks([t + w * (len(models) - 1) / 2 for t in range(len(tasks))], tasks)
    ax.set(ylabel="acc_norm", title="Zero-shot benchmarks (n=500 each)")
    ax.legend(fontsize=7, ncol=3)
    fig.tight_layout()
    fig.savefig(R / "benchmarks.png", dpi=130)


def main():
    loss_curves()
    md = ["# Result tables (auto-generated by evaluation/make_report.py)\n"]
    if s := load("pretrain_summary.json"):
        md += ["## Pre-training", md_table([s], "")]
    if t := load("tokenizer_report.json"):
        md += ["## Tokenizer vs GPT-2 (bytes per token, higher = better compression)",
               md_table([{"split": k, **v} for k, v in t["heldout"].items()], "split")]
    if b := load("benchmarks.json"):
        bench_chart(b)
        rows = [{"model": m, **{t: b[m][t]["acc_norm"] for t in b["_chance"] if t in b[m]}}
                for m in b if not m.startswith("_")]
        md += ["## Benchmarks (acc_norm, n=500 per task, chance = 0.25)", md_table(rows, "model")]
    if r := load("retrieval_ablation.json"):
        for sec, title in (("A_mode_x_rerank", "Retriever x reranker (chunk 128/32)"),
                           ("B_chunking", "Chunk size / overlap (hybrid + rerank)"),
                           ("C_embedder", "Embedding model (dense only)")):
            md += [f"## Retrieval: {title}", md_table([{"config": k, **v} for k, v in r[sec].items()], "config")]
    if q := load("qa_experiments.json"):
        for g, rows in sorted(q.items()):
            md += [f"## QA: {g}", md_table([{"system": k, **v} for k, v in rows.items()], "system")]
    for name, title in (("sft_history.json", "SFT"), ("dpo_history.json", "DPO"), ("reward_model.json", "Reward model")):
        if h := load(name):
            md += [f"## {title} history", md_table(h, "epoch")]
    (R / "TABLES.md").write_text("\n\n".join(md) + "\n", encoding="utf-8")
    print("wrote", R / "TABLES.md")


if __name__ == "__main__":
    main()
